import type { FastifyInstance } from "fastify";
import type { Database } from "@totalbase/database";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import type { AppContext } from "./context.js";
import { createTestApiToken, setupTestApp } from "./test-support.js";

/**
 * The generated Data API OpenAPI document checked against the real HTTP
 * surface: a body built only from what the document says (its create
 * schema's `required` list) must be accepted, and a column the document
 * leaves out of the write body (GENERATED) must be rejected by the API.
 */
describe("GET /api/openapi.json (integration)", () => {
  let app: FastifyInstance;
  let context: AppContext;
  let database: Database;
  let roleId: string;
  let resourceId: string;
  let apiKeyPlain: string;
  let apiKeyUserId: string;
  let apiKeyId: string;

  const TABLE = "openapi_server_test_orders";
  const PATH = `/api/public/table/${TABLE}`;

  beforeAll(async () => {
    ({ app, context, database } = await setupTestApp());

    await database.query(`DROP TABLE IF EXISTS public.${TABLE} CASCADE`);
    await database.query(`
      CREATE TABLE public.${TABLE} (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        customer text NOT NULL,
        quantity integer NOT NULL,
        status text NOT NULL DEFAULT 'NEW',
        note text,
        quantity_x2 integer GENERATED ALWAYS AS (quantity * 2) STORED
      )
    `);
    const { rows } = await database.query<{ id: string }>(
      `INSERT INTO totalbase.resources (postgres_oid, "schema", name, type, status, exposed_methods)
       VALUES (to_regclass($1)::oid, 'public', $2, 'TABLE', 'ACTIVE', ARRAY['GET', 'POST'])
       RETURNING id`,
      [`public.${TABLE}`, TABLE],
    );
    resourceId = rows[0]!.id;

    const role = await context.roles.create("openapi-server-test-role", { apiAccess: true });
    roleId = role.id;
    const fields = ["id", "customer", "quantity", "status", "note", "quantity_x2"].map((field) => ({ field, effect: "ALLOW" as const }));
    await context.permissions.set(roleId, resourceId, "READ", { effect: "ALLOW", fields });
    await context.permissions.set(roleId, resourceId, "CREATE", { effect: "ALLOW", fields });

    const token = await createTestApiToken(context, {
      name: "openapi-server-test-key",
      roleId,
      email: "openapi-server-test-key-owner@example.com",
    });
    ({ plainKey: apiKeyPlain, userId: apiKeyUserId, tokenId: apiKeyId } = token);
  });

  afterAll(async () => {
    await database.query(`DELETE FROM totalbase.tokens WHERE id = $1`, [apiKeyId]);
    await database.query(`DELETE FROM totalbase.users WHERE id = $1`, [apiKeyUserId]);
    await database.query(`DELETE FROM totalbase.roles WHERE id = $1`, [roleId]);
    await database.query(`DELETE FROM totalbase.resources WHERE id = $1`, [resourceId]);
    await database.query(`DROP TABLE IF EXISTS public.${TABLE} CASCADE`);
    await app.close();
    await database.close();
  });

  async function fetchSpec() {
    const res = await app.inject({ method: "GET", url: "/api/openapi.json", headers: { authorization: `Bearer ${apiKeyPlain}` } });
    expect(res.statusCode).toBe(200);
    return res.json();
  }

  it("points `servers` at the configured public URL", async () => {
    const spec = await fetchSpec();
    expect(spec.servers).toEqual([{ url: (await context.auth.mailer.publicUrl()).replace(/\/+$/, "") }]);
  });

  it("accepts a body built only from the documented required fields", async () => {
    const spec = await fetchSpec();
    const create = spec.components.schemas[`public_${TABLE}_create`];
    expect(create.required).toEqual(["customer", "quantity"]);

    const sample: Record<string, unknown> = { string: "acme", integer: 3 };
    const data = Object.fromEntries(
      (create.required as string[]).map((field) => [field, sample[create.properties[field].type as string]]),
    );
    const res = await app.inject({ method: "POST", url: PATH, headers: { authorization: `Bearer ${apiKeyPlain}` }, payload: { data } });
    expect(res.statusCode).toBe(201);
    expect(spec.paths[PATH].post.responses["201"]).toBeDefined();
    expect(res.json().data).toMatchObject({ customer: "acme", quantity: 3, status: "NEW", quantity_x2: 6 });
  });

  it("leaves GENERATED columns out of the write body, which the API indeed rejects", async () => {
    const spec = await fetchSpec();
    expect(spec.components.schemas[`public_${TABLE}_create`].properties).not.toHaveProperty("quantity_x2");
    expect(spec.components.schemas[`public_${TABLE}`].properties).toHaveProperty("quantity_x2");

    const res = await app.inject({
      method: "POST",
      url: PATH,
      headers: { authorization: `Bearer ${apiKeyPlain}` },
      payload: { data: { customer: "acme", quantity: 1, quantity_x2: 99 } },
    });
    // PostgreSQL's 428C9, mapped - not a 500.
    expect(res.statusCode).toBe(400);
    expect(res.json().errors[0]).toMatchObject({ source: "POSTGRESQL", code: "GENERATED_ALWAYS" });
  });

  describe("GET /admin/api/openapi/data", () => {
    let adminToken: string;

    beforeAll(async () => {
      ({ token: adminToken } = await context.auth.login(
        { email: process.env["TOTALBASE_ADMIN_EMAIL"]!, password: process.env["TOTALBASE_ADMIN_PASSWORD"]!, ip: "127.0.0.1", userAgent: "openapi-test" },
        () => {},
      ));
    });

    function adminGet(url: string, token = adminToken) {
      return app.inject({ method: "GET", url, headers: { authorization: `Bearer ${token}` } });
    }

    it("returns the same document the role's own API key gets with as=api_key", async () => {
      const asAdmin = await adminGet(`/admin/api/openapi/data?role=${roleId}&as=api_key`);
      expect(asAdmin.statusCode).toBe(200);
      expect(asAdmin.json()).toEqual(await fetchSpec());
    });

    it("defaults to a signed-in user holding the role, which adds the session-only routes", async () => {
      const paths = (await adminGet(`/admin/api/openapi/data?role=${roleId}`)).json().paths;
      expect(paths["/api/auth/me"]?.get).toBeDefined();
      expect(paths["/api/tokens"]?.get).toBeDefined();
    });

    it("rejects a missing or unknown role", async () => {
      expect((await adminGet("/admin/api/openapi/data")).statusCode).toBe(400);
      expect((await adminGet("/admin/api/openapi/data?role=not-a-uuid")).statusCode).toBe(404);
      expect((await adminGet("/admin/api/openapi/data?role=00000000-0000-0000-0000-000000000000")).statusCode).toBe(404);
    });

    it("is admin-only", async () => {
      const res = await adminGet(`/admin/api/openapi/data?role=${roleId}`, apiKeyPlain);
      expect(res.statusCode).toBeGreaterThanOrEqual(401);
      expect(res.statusCode).toBeLessThanOrEqual(403);
    });
  });

  describe("GET /admin/api/endpoints", () => {
    let adminToken: string;

    beforeAll(async () => {
      ({ token: adminToken } = await context.auth.login(
        { email: process.env["TOTALBASE_ADMIN_EMAIL"]!, password: process.env["TOTALBASE_ADMIN_PASSWORD"]!, ip: "127.0.0.1", userAgent: "openapi-test" },
        () => {},
      ));
    });

    async function endpoints() {
      const res = await app.inject({ method: "GET", url: "/admin/api/endpoints", headers: { authorization: `Bearer ${adminToken}` } });
      expect(res.statusCode).toBe(200);
      return res.json().data as { method: string; path: string; kind: string; enabled: boolean; workflow: string | null; access: string }[];
    }

    it("lists every route of an exposed resource, a method it doesn't expose as disabled", async () => {
      const rows = (await endpoints()).filter((e) => e.path.startsWith(PATH));
      expect(rows.find((e) => e.method === "GET" && e.path === PATH)).toMatchObject({ kind: "TABLE", enabled: true });
      expect(rows.find((e) => e.method === "POST")).toMatchObject({ enabled: true });
      expect(rows.find((e) => e.method === "DELETE" && e.path === `${PATH}/{pk}`)).toMatchObject({ enabled: false });
    });

    it("lists the fixed routes with their access", async () => {
      const rows = await endpoints();
      expect(rows.find((e) => e.method === "POST" && e.path === "/api/auth/login")).toMatchObject({ kind: "SYSTEM", access: "public", enabled: true });
    });

    it("lists a workflow as disabled until it is enabled and published", async () => {
      let workflow = await context.workflowsAdmin.create({
        name: "Endpoints test flow",
        slug: "endpoints-test-flow",
        startConfiguration: { trigger: "WEBHOOK", method: "GET", access: "PUBLIC" },
      });
      try {
        const find = async () => (await endpoints()).find((e) => e.workflow === workflow.id);
        expect(await find()).toMatchObject({ method: "GET", path: "/api/workflows/endpoints-test-flow/webhook", access: "public", enabled: false });
        workflow = await context.workflowsAdmin.publish(workflow.id, workflow.revision, () => {});
        await context.workflowsAdmin.update(workflow.id, { revision: workflow.revision, enabled: true });
        expect(await find()).toMatchObject({ enabled: true });
      } finally {
        await context.workflowsAdmin.remove(workflow.id);
      }
    });

    it("is admin-only", async () => {
      const res = await app.inject({ method: "GET", url: "/admin/api/endpoints", headers: { authorization: `Bearer ${apiKeyPlain}` } });
      expect(res.statusCode).toBeGreaterThanOrEqual(401);
      expect(res.statusCode).toBeLessThanOrEqual(403);
    });
  });

  describe("fixed routes (auth, tokens, transactions, files, ...)", () => {
    it("lists public auth routes without security, and leaves session-only routes out for an API key", async () => {
      const spec = await fetchSpec();
      expect(spec.paths["/api/auth/login"].post.security).toEqual([]);
      expect(spec.paths["/api/auth/password/forgot"].post.security).toEqual([]);
      expect(spec.paths["/api/auth/oauth/{provider}"].get.responses["302"]).toBeDefined();
      expect(spec.paths["/api/auth/me"]).toBeUndefined();
      expect(spec.paths["/api/tokens"]).toBeUndefined();
      expect(spec.paths["/api/executions/{id}"].get).toBeDefined();
      expect(spec.components.schemas["Session"]).toBeDefined();
    });

    it("lists register only while public registration is enabled", async () => {
      const original = await context.settings.get("auth.registration_enabled");
      try {
        await context.settings.set("auth.registration_enabled", false);
        expect((await fetchSpec()).paths["/api/auth/register"]).toBeUndefined();
        await context.settings.set("auth.registration_enabled", true);
        expect((await fetchSpec()).paths["/api/auth/register"].post.security).toEqual([]);
      } finally {
        await context.settings.set("auth.registration_enabled", original);
      }
    });

    it("lists transactions only for a role holding the transactions grant", async () => {
      expect((await fetchSpec()).paths["/api/transactions"]).toBeUndefined();
      await context.capabilityPermissions.setGrant(roleId, "TRANSACTIONS", "ALLOW");
      const operation = (await fetchSpec()).paths["/api/transactions"].post;
      expect(operation.parameters.map((p: { name: string }) => p.name)).toEqual(["Idempotency-Key", "Prefer"]);
    });

    it("lists a published workflow at its own literal path only once the role may invoke it", async () => {
      let workflow = await context.workflowsAdmin.create({
        name: "OpenAPI server test flow",
        slug: "openapi-server-test-flow",
        startConfiguration: { trigger: "MANUAL" },
      });
      try {
        workflow = await context.workflowsAdmin.publish(workflow.id, workflow.revision, () => {});
        await context.workflowsAdmin.update(workflow.id, { revision: workflow.revision, enabled: true });
        const path = "/api/workflows/openapi-server-test-flow/run";
        expect((await fetchSpec()).paths[path]).toBeUndefined();

        await context.workflowPermissions.grant(roleId, workflow.id);
        const paths = (await fetchSpec()).paths;
        expect(paths[path].post.summary).toBe("OpenAPI server test flow");
        expect(paths["/api/workflows/runs/{runId}/result"].get).toBeDefined();
      } finally {
        await context.workflowsAdmin.remove(workflow.id);
      }
    });

    it("lists each Files route only for the action the role holds on files", async () => {
      const { rows } = await database.query<{ id: string }>(
        `SELECT id FROM totalbase.resources WHERE "schema" = 'totalbase' AND name = 'files'`,
      );
      expect((await fetchSpec()).paths["/api/totalbase/table/files"]).toBeUndefined();
      await context.permissions.set(roleId, rows[0]!.id, "CREATE", { effect: "ALLOW" });
      const paths = (await fetchSpec()).paths;
      expect(paths["/api/totalbase/table/files"].post.requestBody.content["multipart/form-data"]).toBeDefined();
      expect(paths["/api/totalbase/table/files/{id}"]).toBeUndefined(); // no READ/UPDATE/DELETE
    });
  });

  describe("openapi.* settings", () => {
    const KEYS = ["openapi.enabled", "openapi.include_examples", "openapi.cache_enabled"] as const;
    const saved = new Map<string, { overridden: boolean; value: unknown }>();

    beforeAll(async () => {
      for (const key of KEYS) saved.set(key, { overridden: await context.settings.isOverridden(key), value: await context.settings.get(key) });
    });

    afterAll(async () => {
      // Shared with local development: leave these as they were.
      for (const key of KEYS) {
        const entry = saved.get(key)!;
        if (entry.overridden) await context.settings.set(key, entry.value as never);
        else await context.settings.reset(key);
      }
    });

    it("adds sample values only with openapi.include_examples", async () => {
      await context.settings.set("openapi.include_examples", true);
      expect((await fetchSpec()).components.schemas[`public_${TABLE}`].properties.quantity.examples).toEqual([1]);
      await context.settings.set("openapi.include_examples", false);
      expect((await fetchSpec()).components.schemas[`public_${TABLE}`].properties.quantity).not.toHaveProperty("examples");
    });

    it("serves a cached document until PostgreSQL's revision moves - whoever wrote", async () => {
      await context.settings.set("openapi.cache_enabled", true);
      expect((await fetchSpec()).paths[PATH].post).toBeDefined();
      // Plain SQL, no API involved: the trigger still bumps the revision.
      await database.query(`UPDATE totalbase.resources SET exposed_methods = ARRAY['GET'] WHERE id = $1`, [resourceId]);
      try {
        expect((await fetchSpec()).paths[PATH].post).toBeUndefined();
      } finally {
        await database.query(`UPDATE totalbase.resources SET exposed_methods = ARRAY['GET', 'POST'] WHERE id = $1`, [resourceId]);
      }
      expect((await fetchSpec()).paths[PATH].post).toBeDefined();
    });

    it("answers 404 while openapi.enabled is off; the admin's view of a role's document still works", async () => {
      await context.settings.set("openapi.enabled", false);
      const res = await app.inject({ method: "GET", url: "/api/openapi.json", headers: { authorization: `Bearer ${apiKeyPlain}` } });
      expect(res.statusCode).toBe(404);
      await context.settings.set("openapi.enabled", true);
      expect((await fetchSpec()).paths[PATH]).toBeDefined();
    });
  });
});


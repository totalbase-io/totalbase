const OPTIONS = { publicUrl: "https://api.example.com/" };

const MIGRATIONS_DIR = fileURLToPath(new URL("../../../migrations/totalbase", import.meta.url));

describe("postgresTypeToSchema", () => {
  it("maps common PostgreSQL types", () => {
    expect(postgresTypeToSchema("uuid")).toEqual({ type: "string", format: "uuid" });
    expect(postgresTypeToSchema("character varying(255)")).toEqual({ type: "string" });
    expect(postgresTypeToSchema("numeric(12,2)")).toEqual({ type: "number" });
    expect(postgresTypeToSchema("timestamp with time zone")).toEqual({ type: "string", format: "date-time" });
    expect(postgresTypeToSchema("text[]")).toEqual({ type: "array", items: { type: "string" } });
    expect(postgresTypeToSchema("jsonb")).toEqual({});
  });

  it("adds a sample value when asked - none for json, which has no honest one", () => {
    expect(postgresTypeToSchema("uuid", true).examples).toEqual(["3fa85f64-5717-4562-b3fc-2c963f66afa6"]);
    expect(postgresTypeToSchema("integer[]", true)).toEqual({ type: "array", items: { type: "integer" }, examples: [[1]] });
    expect(postgresTypeToSchema("jsonb", true)).toEqual({});
  });
});

describe("withNull", () => {
  it("uses OpenAPI 3.1 type arrays, not 3.0's nullable", () => {
    expect(withNull({ type: "string", format: "uuid" })).toEqual({ type: ["string", "null"], format: "uuid" });
    expect(withNull({ type: ["string", "null"] })).toEqual({ type: ["string", "null"] });
    expect(withNull({})).toEqual({}); // json/jsonb: already accepts null
  });
});

describe("buildFunctionSpec", () => {
  const detail = { parameters: [{ name: "invoice", dataType: "integer", hasDefault: false }], returnsRows: false } as unknown as Parameters<typeof buildFunctionSpec>[0]["detail"];

  it("documents the resource's function_class: x-totalbase-function-class, and QUERY as safe", () => {
    const query = buildFunctionSpec({ schema: "public", name: "total", detail, functionClass: "QUERY" }).pathItem.post!;
    expect(query["x-totalbase-function-class"]).toBe("QUERY");
    expect(query.description).toMatch(/only reads - safe/);
    const action = buildFunctionSpec({ schema: "public", name: "pay", detail, functionClass: "ACTION" }).pathItem.post!;
    expect(action["x-totalbase-function-class"]).toBe("ACTION");
    expect(action.description).toMatch(/changes data/);
    expect(buildFunctionSpec({ schema: "public", name: "x", detail, functionClass: "UNCLASSIFIED" }).pathItem.post!["x-totalbase-function-class"]).toBe("UNCLASSIFIED");
  });
});

describe("@totalbase/openapi (integration)", () => {
  let database: Database;
  let effectivePermissions: EffectivePermissionService;
  let roleId: string;
  let tableResourceId: string;
  let viewResourceId: string;

  beforeAll(async () => {
    database = new Database(loadDatabaseConfigFromEnv());
    await runMigrations(database, { migrationsDir: MIGRATIONS_DIR, totalbaseVersion: "0.0.0-test" });
    effectivePermissions = new EffectivePermissionService(database);

    await database.query(`DROP TABLE IF EXISTS public.openapi_pkg_test_items`);
    await database.query(`DROP VIEW IF EXISTS public.openapi_pkg_test_view`);
    await database.query(`
      CREATE TABLE public.openapi_pkg_test_items (
        id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
        name text NOT NULL,
        secret text NOT NULL,
        price numeric(10,2),
        price_x2 numeric GENERATED ALWAYS AS (price * 2) STORED,
        pin text,
        seq integer GENERATED BY DEFAULT AS IDENTITY,
        note text NOT NULL DEFAULT ''
      )
    `);
    await database.query(`
      CREATE VIEW public.openapi_pkg_test_view AS SELECT id, name FROM public.openapi_pkg_test_items
    `);

    const snapshot = await buildCatalogSnapshot(database);
    await reconcileResources(database, snapshot);

    await database.query(
      `UPDATE totalbase.resources SET exposed_methods = CASE type WHEN 'TABLE' THEN '{GET,POST,PATCH,DELETE}'::text[] ELSE '{GET}'::text[] END
       WHERE "schema" = 'public' AND name IN ('openapi_pkg_test_items', 'openapi_pkg_test_view')`,
    );

    const { rows: resourceRows } = await database.query<{ id: string; name: string }>(
      `SELECT id, name FROM totalbase.resources WHERE "schema" = 'public'
       AND name IN ('openapi_pkg_test_items', 'openapi_pkg_test_view')`,
    );
    tableResourceId = resourceRows.find((r) => r.name === "openapi_pkg_test_items")!.id;
    viewResourceId = resourceRows.find((r) => r.name === "openapi_pkg_test_view")!.id;

    const { rows: roleRows } = await database.query<{ id: string }>(
      `INSERT INTO totalbase.roles (name) VALUES ('openapi-pkg-test-role') RETURNING id`,
    );
    roleId = roleRows[0]!.id;

    const { rows: permissionRows } = await database.query<{ id: string }>(
      `INSERT INTO totalbase.permissions (role, resource, action, effect)
       VALUES ($1, $2, 'READ', 'ALLOW') RETURNING id`,
      [roleId, tableResourceId],
    );
    await database.query(
      `UPDATE totalbase.permissions SET field_overrides = $2 WHERE id = $1`,
      [
        permissionRows[0]!.id,
        JSON.stringify([
          { field: "id", effect: "ALLOW" },
          { field: "name", effect: "ALLOW" },
          { field: "price", effect: "ALLOW" },
        ]),
      ],
    );
    // CREATE may write `secret`, which READ never returns; `pin` is a Password column.
    await database.query(
      `INSERT INTO totalbase.permissions (role, resource, action, effect, field_overrides) VALUES ($1, $2, 'CREATE', 'ALLOW', $3)`,
      [
        roleId,
        tableResourceId,
        JSON.stringify(["id", "name", "secret", "price", "price_x2", "pin", "seq", "note"].map((field) => ({ field, effect: "ALLOW" }))),
      ],
    );
    await database.query(
      `INSERT INTO totalbase.resources_columns (resource, attnum, name, config)
       SELECT $1, attnum, attname, '{"input": "password"}'::jsonb FROM pg_attribute
       WHERE attrelid = 'public.openapi_pkg_test_items'::regclass AND attname = 'pin'`,
      [tableResourceId],
    );
  });

  afterAll(async () => {
    await database.query(`DELETE FROM totalbase.roles WHERE id = $1`, [roleId]);
    await database.query(`DROP TABLE IF EXISTS public.openapi_pkg_test_items CASCADE`);
    await database.query(`DROP VIEW IF EXISTS public.openapi_pkg_test_view`);
    await database.query(`DELETE FROM totalbase.resources WHERE id IN ($1, $2)`, [tableResourceId, viewResourceId]);
    await database.close();
  });

  it("lists only ALLOW'd actions and only ALLOW'd fields for the requesting principal", async () => {
    const spec = await buildPublicOpenApiSpec(database, effectivePermissions, [roleId], OPTIONS);

    const collectionPath = spec.paths["/api/public/table/openapi_pkg_test_items"];
    expect(collectionPath?.get).toBeDefined();
    expect(collectionPath?.post).toBeDefined();
    expect(collectionPath?.patch).toBeUndefined(); // no UPDATE grant
    expect(collectionPath?.delete).toBeUndefined(); // no DELETE grant

    const schema = spec.components?.schemas?.["public_openapi_pkg_test_items"];
    expect(schema?.properties).toHaveProperty("name");
    expect(schema?.properties).toHaveProperty("price");
    expect(schema?.properties).not.toHaveProperty("secret"); // no field grant
    expect(schema?.["x-totalbase-fields"]).toEqual(["id", "name", "price"]);
  });

  it("builds the create body from the CREATE grant, with required/generated/password handled like PostgreSQL does", async () => {
    const spec = await buildPublicOpenApiSpec(database, effectivePermissions, [roleId], OPTIONS);
    const create = spec.components?.schemas?.["public_openapi_pkg_test_items_create"];

    // CREATE's own field grant, not READ's: `secret` is writable though never readable.
    expect(Object.keys(create?.properties ?? {})).toEqual(["id", "name", "secret", "price", "pin", "seq", "note"]);
    // GENERATED columns can't take a value.
    expect(create?.properties).not.toHaveProperty("price_x2");
    // Only NOT NULL + no default + not identity/generated.
    expect(create?.required).toEqual(["name", "secret"]);
    expect(create?.additionalProperties).toBe(false);
    // Password columns: write-only, and never part of the returned row.
    expect(create?.properties?.["pin"]).toMatchObject({ format: "password", writeOnly: true });
    expect(spec.components?.schemas?.["public_openapi_pkg_test_items"]?.properties).not.toHaveProperty("pin");

    const post = spec.paths["/api/public/table/openapi_pkg_test_items"]?.post;
    expect(post?.responses["201"]).toBeDefined(); // the route answers 201, not 200
    expect(post?.responses["200"]).toBeUndefined();
    expect(post?.parameters?.map((p) => p.name)).toEqual(["bulk", "Idempotency-Key"]);
  });

  it("describes a no-READ principal's mutation responses as the primary key only", async () => {
    const { rows } = await database.query<{ id: string }>(
      `INSERT INTO totalbase.roles (name) VALUES ('openapi-pkg-test-create-only') RETURNING id`,
    );
    const createOnly = rows[0]!.id;
    try {
      await database.query(
        `INSERT INTO totalbase.permissions (role, resource, action, effect, field_overrides) VALUES ($1, $2, 'CREATE', 'ALLOW', $3)`,
        [createOnly, tableResourceId, JSON.stringify([{ field: "name", effect: "ALLOW" }, { field: "secret", effect: "ALLOW" }])],
      );
      const spec = await buildPublicOpenApiSpec(database, effectivePermissions, [createOnly], OPTIONS);
      expect(Object.keys(spec.components?.schemas?.["public_openapi_pkg_test_items"]?.properties ?? {})).toEqual(["id"]);
    } finally {
      await database.query(`DELETE FROM totalbase.roles WHERE id = $1`, [createOnly]);
    }
  });

  it("applies the injected field guard to every grant, the way the Data API does", async () => {
    const spec = await buildPublicOpenApiSpec(database, effectivePermissions, [roleId], {
      ...OPTIONS,
      guardFieldDecision: (_resource, _action, decision) => (field) => (field === "name" ? "DENY" : decision(field)),
    });
    expect(spec.components?.schemas?.["public_openapi_pkg_test_items"]?.properties).not.toHaveProperty("name");
    expect(spec.components?.schemas?.["public_openapi_pkg_test_items_create"]?.properties).not.toHaveProperty("name");
  });

  it("omits a resource entirely when the principal has no allowed action on it", async () => {
    const spec = await buildPublicOpenApiSpec(database, effectivePermissions, [roleId], OPTIONS);
    expect(spec.paths["/api/public/view/openapi_pkg_test_view"]).toBeUndefined();
  });

  it("produces an empty-but-valid spec for a principal with no roles", async () => {
    const spec = await buildPublicOpenApiSpec(database, effectivePermissions, [], OPTIONS);
    expect(spec.paths["/api/public/table/openapi_pkg_test_items"]).toBeUndefined();
    expect(spec.openapi).toBe("3.1.0");
  });

  it("marks nullable columns with a 3.1 type array and never emits `nullable`", async () => {
    const spec = await buildPublicOpenApiSpec(database, effectivePermissions, [roleId], OPTIONS);
    const properties = spec.components?.schemas?.["public_openapi_pkg_test_items"]?.properties;
    expect(properties?.["price"]).toEqual({ type: ["number", "null"] });
    expect(properties?.["name"]).toEqual({ type: "string" });
    expect(JSON.stringify(spec)).not.toContain('"nullable"');
  });

  it("declares servers from the public URL, bearer security, and the shared error envelope", async () => {
    const spec = await buildPublicOpenApiSpec(database, effectivePermissions, [roleId], OPTIONS);
    expect(spec.servers).toEqual([{ url: "https://api.example.com" }]);
    expect(spec.security).toEqual([{ bearerAuth: [] }]);
    expect(spec.components?.securitySchemes?.["bearerAuth"]).toMatchObject({ type: "http", scheme: "bearer" });
    expect(spec.components?.schemas?.["Error"]).toBeDefined();

    const collection = spec.paths["/api/public/table/openapi_pkg_test_items"];
    expect(collection?.get?.responses["401"]).toEqual({ $ref: "#/components/responses/Unauthorized" });
    expect(collection?.get?.responses["409"]).toBeUndefined(); // reads don't conflict
    expect(collection?.post?.responses["409"]).toEqual({ $ref: "#/components/responses/Conflict" });
    expect(collection?.post?.responses["422"]).toEqual({ $ref: "#/components/responses/UnprocessableEntity" });
    expect(collection?.post?.responses["413"]).toEqual({ $ref: "#/components/responses/PayloadTooLarge" });
    expect(collection?.get?.operationId).toBe("list_public_openapi_pkg_test_items");
    expect(collection?.post?.operationId).toBe("create_public_openapi_pkg_test_items");

    // Every $ref resolves inside the document.
    const refs = [...JSON.stringify(spec).matchAll(/"\$ref":"#\/components\/(\w+)\/(\w+)"/g)];
    for (const [, section, name] of refs) {
      expect((spec.components as Record<string, Record<string, unknown>>)[section!]?.[name!], `${section}/${name}`).toBeDefined();
    }
  });

  it("exposes a single-pk item path only for a single-column primary key", async () => {
    const spec = await buildPublicOpenApiSpec(database, effectivePermissions, [roleId], OPTIONS);
    expect(spec.paths["/api/public/table/openapi_pkg_test_items/{pk}"]?.get).toBeDefined();
  });
});

describe("buildAdminOpenApiSpec", () => {
  it("converts Fastify :param syntax to OpenAPI {param} syntax and groups by path", () => {
    const spec = buildAdminOpenApiSpec([
      { method: "GET", url: "/admin/api/users" },
      { method: "GET", url: "/admin/api/users/:id" },
      { method: "PATCH", url: "/admin/api/users/:id" },
      { method: "HEAD", url: "/admin/api/users" },
    ], OPTIONS);
    expect(spec.paths["/admin/api/users"]?.get).toBeDefined();
    expect(spec.paths["/admin/api/users/{id}"]?.get).toBeDefined();
    expect(spec.paths["/admin/api/users/{id}"]?.patch).toBeDefined();
    expect((spec.paths["/admin/api/users"] as Record<string, unknown>)["head"]).toBeUndefined();
  });

  it("requires bearer auth by default and marks public routes with an empty security list", () => {
    const spec = buildAdminOpenApiSpec([
      { method: "GET", url: "/admin/api/users" },
      { method: "POST", url: "/admin/api/auth/login", public: true },
    ], OPTIONS);
    expect(spec.servers).toEqual([{ url: "https://api.example.com" }]);
    expect(spec.security).toEqual([{ bearerAuth: [] }]);
    expect(spec.paths["/admin/api/users"]?.get?.security).toBeUndefined();
    expect(spec.paths["/admin/api/auth/login"]?.post?.security).toEqual([]);
  });

  it("declares every path parameter and gives each operation a unique operationId", () => {
    const spec = buildAdminOpenApiSpec([
      { method: "GET", url: "/admin/api/roles/:role/resources/:resource" },
      { method: "GET", url: "/admin/api/users-x" },
      { method: "GET", url: "/admin/api/users_x" },
    ], OPTIONS);
    const operation = spec.paths["/admin/api/roles/{role}/resources/{resource}"]?.get;
    expect(operation?.operationId).toBe("get_roles_role_resources_resource");
    expect(operation?.parameters?.map((p) => [p.name, p.in, p.required])).toEqual([
      ["role", "path", true],
      ["resource", "path", true],
    ]);
    // "users-x" and "users_x" sanitize to the same id - the second is suffixed.
    expect(spec.paths["/admin/api/users-x"]?.get?.operationId).toBe("get_users_x");
    expect(spec.paths["/admin/api/users_x"]?.get?.operationId).toBe("get_users_x_2");
  });
});

describe("buildRouteOperation", () => {
  it("derives path params, marks public routes, and adds write error statuses", () => {
    const { path, method, operation } = buildRouteOperation({
      method: "POST",
      url: "/api/tokens/:id/rotate",
      doc: {
        summary: "Rotate",
        tags: ["tokens"],
        access: "session",
        requestBody: { schema: { type: "object" } },
        response: { status: "200" },
      },
    });
    expect(path).toBe("/api/tokens/{id}/rotate");
    expect(method).toBe("post");
    expect(operation.operationId).toBe("post_tokens_id_rotate");
    expect(operation.parameters).toEqual([{ name: "id", in: "path", required: true, schema: { type: "string" } }]);
    expect(Object.keys(operation.responses)).toEqual(expect.arrayContaining(["409", "413", "422"]));
    expect(operation.security).toBeUndefined();

    const login = buildRouteOperation({
      method: "POST",
      url: "/api/auth/login",
      doc: { summary: "Login", tags: ["auth"], access: "public", response: { status: "200" } },
    });
    expect(login.operation.security).toEqual([]);
  });

  it("hides session-only routes from an API key and honors `visible`", async () => {
    const session = { summary: "Me", tags: ["auth"], access: "session" as const, response: { status: "200" as const } };
    expect(await isRouteVisible(session, { roleIds: [], principalType: "USER" })).toBe(true);
    expect(await isRouteVisible(session, { roleIds: [], principalType: "API_KEY" })).toBe(false);
    const gated = { ...session, access: "principal" as const, visible: (viewer: OpenApiViewer) => viewer.roleIds.includes("r1") };
    expect(await isRouteVisible(gated, { roleIds: ["r1"], principalType: "API_KEY" })).toBe(true);
    expect(await isRouteVisible(gated, { roleIds: [], principalType: "API_KEY" })).toBe(false);
  });
});

describe("buildWorkflowPaths", () => {
  const base = { name: "Sync orders", description: null, method: "POST" as const, access: "AUTHENTICATED" as const, responseMode: "SYNC" as const };

  it("gives each workflow its own literal path, per trigger kind", () => {
    const { paths } = buildWorkflowPaths([
      { ...base, slug: "sync-orders", trigger: "MANUAL" },
      { ...base, slug: "stripe-hook", trigger: "WEBHOOK", access: "PUBLIC", responseMode: "ASYNC" },
      { ...base, slug: "lookup", trigger: "WEBHOOK", method: "GET" },
    ]);
    expect(paths["/api/workflows/sync-orders/run"]?.post?.summary).toBe("Sync orders");
    const hook = paths["/api/workflows/stripe-hook/webhook"]?.post;
    expect(hook?.security).toEqual([]); // PUBLIC webhook
    expect(hook?.responses["202"]).toBeDefined(); // ASYNC
    expect(paths["/api/workflows/lookup/webhook"]?.get?.responses["504"]).toBeDefined(); // SYNC can time out
    expect(paths["/api/workflows/runs/{runId}/result"]?.get).toBeDefined();
  });

  it("adds nothing when the viewer can invoke no workflow", () => {
    expect(buildWorkflowPaths([]).paths).toEqual({});
  });
});

describe("listApiEndpoints", () => {
  const workflow = { id: "w1", name: "Sync", slug: "sync", method: "POST" as const, access: "AUTHENTICATED" as const, live: true };

  it("lists every route of a resource, flagging methods outside exposed_methods as disabled", () => {
    const endpoints = listApiEndpoints({
      resources: [
        { id: "r1", schema: "public", name: "orders", type: "TABLE", exposedMethods: ["GET"] },
        { id: "r2", schema: "public", name: "tax", type: "FUNCTION", exposedMethods: ["POST"] },
      ],
      workflows: [],
      routes: [],
    });
    const orders = endpoints.filter((e) => e.resource === "r1");
    expect(orders.map((e) => `${e.method} ${e.path} ${e.enabled}`)).toEqual([
      "GET /api/public/table/orders true",
      "GET /api/public/table/orders/{pk} true",
      "POST /api/public/table/orders false",
      "PATCH /api/public/table/orders false",
      "PATCH /api/public/table/orders/{pk} false",
      "DELETE /api/public/table/orders false",
      "DELETE /api/public/table/orders/{pk} false",
    ]);
    expect(endpoints.find((e) => e.resource === "r2")).toMatchObject({ method: "POST", path: "/api/public/function/tax", kind: "FUNCTION", enabled: true });
  });

  it("lists HTTP-triggered workflows, live or not, plus the run-result route; skips DATA_EVENT", () => {
    const endpoints = listApiEndpoints({
      resources: [],
      workflows: [
        { ...workflow, trigger: "MANUAL" },
        { ...workflow, id: "w2", slug: "hook", trigger: "WEBHOOK", method: "GET", access: "PUBLIC", live: false },
        { ...workflow, id: "w3", slug: "on-insert", trigger: "DATA_EVENT" },
      ],
      routes: [],
    });
    expect(endpoints.map((e) => `${e.method} ${e.path} ${e.access} ${e.enabled}`)).toEqual([
      "POST /api/workflows/sync/run principal true",
      "GET /api/workflows/hook/webhook public false",
      "GET /api/workflows/runs/{runId}/result principal true",
    ]);
  });

  it("lists fixed routes with OpenAPI path syntax and their own access", () => {
    const [endpoint] = listApiEndpoints({
      resources: [],
      workflows: [],
      routes: [{ method: "DELETE", url: "/api/tokens/:id", doc: { summary: "Revoke a token", tags: ["tokens"], access: "session", response: { status: "204" } } }],
    });
    expect(endpoint).toMatchObject({ method: "DELETE", path: "/api/tokens/{id}", kind: "SYSTEM", name: "Revoke a token", access: "session", tag: "tokens" });
  });
});

import { describe, expect, it } from "vitest";
import {
  CREATABLE_VARIABLE_KINDS,
  isValidValue,
  resourceQueryColumns,
  validateRecordConfig,
  validateVariables,
  VALUE_TYPES,
  VALUE_TYPE_META,
  VARIABLE_CATALOG,
  variableDependencies,
  widgetsForValueType,
  type VariableDefinition,
} from "./variable-catalog.js";
import { DEFAULT_WIDGETS } from "../columns/column-inputs.js";

const resource = (name: string, where: Record<string, unknown> = {}): VariableDefinition => ({
  name,
  kind: "RESOURCE",
  resource: "3f0c6a0e-0000-4000-8000-000000000001",
  query: { fields: "id,nombre", where },
  mode: "list",
  immediate: true,
  watch: true,
  count: false,
});

describe("VARIABLE_CATALOG", () => {
  it("offers every kind but the generated RECORD", () => {
    expect(CREATABLE_VARIABLE_KINDS).toEqual(["VALUE", "RESOURCE", "CALL"]);
    expect(VARIABLE_CATALOG.RECORD.creatable).toBe(false);
  });

  it("describes every value type, and every one binds to at least one widget - its default among them", () => {
    for (const type of VALUE_TYPES) {
      expect(VALUE_TYPE_META[type].label).toBeTruthy();
      expect(widgetsForValueType(type)).toContain(DEFAULT_WIDGETS[type]);
    }
  });

  it("binds a date range to the date picker, and a number to pickers of a key", () => {
    expect(widgetsForValueType("date_range")).toEqual(["UInputDate"]);
    expect(widgetsForValueType("number")).toEqual(expect.arrayContaining(["UInputNumber", "USelectMenu", "USelect"]));
    expect(widgetsForValueType("number")).not.toContain("UInputDate");
  });
});

describe("isValidValue()", () => {
  it("accepts null for every type", () => {
    for (const type of VALUE_TYPES) expect(isValidValue(type, null)).toBe(true);
  });

  it("checks each type's shape", () => {
    expect(isValidValue("number", 3.5)).toBe(true);
    expect(isValidValue("number", "3")).toBe(false);
    expect(isValidValue("number", Number.NaN)).toBe(false);
    expect(isValidValue("date", "2026-09-29")).toBe(true);
    expect(isValidValue("date", "29/09/2026")).toBe(false);
    expect(isValidValue("time", "23:59")).toBe(true);
    expect(isValidValue("time", "24:00")).toBe(false);
    expect(isValidValue("point", { lng: -58.4, lat: -34.6 })).toBe(true);
    expect(isValidValue("time_range", { from: "09:00", to: "18:00" })).toBe(true);
  });

  it("holds a date range as a known period or two dates", () => {
    expect(isValidValue("date_range", { period: "this_month" })).toBe(true);
    expect(isValidValue("date_range", { from: "2026-09-01", to: "2026-09-30" })).toBe(true);
    expect(isValidValue("date_range", { period: "next_month" })).toBe(false);
    expect(isValidValue("date_range", { period: "this_month", from: "2026-09-01" })).toBe(false);
    expect(isValidValue("date_range", { from: "2026-09-01" })).toBe(false);
  });
});

describe("validateVariables()", () => {
  it("accepts a valid set", () => {
    expect(
      validateVariables([
        { name: "rango", kind: "VALUE", type: "date_range", default: { source: "constant", value: { period: "this_month" } } },
        { name: "cliente", kind: "VALUE", type: "number" },
        resource("ventas", { fecha: { _gte: "{{vars.rango.from}}" }, cliente: { _eq: "{{vars.cliente.value}}" } }),
        { name: "emitir", kind: "CALL", target: { type: "WORKFLOW", workflow: "6a1b0d0e-1f4c-4e1a-9a0b-2f3c4d5e6f70" }, input: { cliente: "{{vars.cliente.value}}" } },
      ]),
    ).toEqual([]);
  });

  it("rejects bad, reserved and repeated names", () => {
    expect(
      validateVariables([
        { name: "Cliente", kind: "VALUE", type: "text" },
        { name: "vars", kind: "VALUE", type: "text" },
        { name: "total", kind: "VALUE", type: "number" },
        { name: "total", kind: "VALUE", type: "number" },
      ]),
    ).toEqual([
      "Cliente: a name starts with a lowercase letter, then letters, digits or _ (at most 32).",
      'vars: "vars" is reserved.',
      "total: the name is used twice.",
    ]);
  });

  it("rejects an unknown kind, a stored RECORD and an unknown value type", () => {
    expect(
      validateVariables([
        { name: "a", kind: "TIMER" },
        { name: "b", kind: "RECORD" },
        { name: "c", kind: "VALUE", type: "money" },
      ]),
    ).toEqual(['a: unknown kind "TIMER".', "b: a Record is generated by the DataView type, not defined.", 'c: unknown value type "money".']);
  });

  it("requires a default that fits the type", () => {
    expect(validateVariables([{ name: "n", kind: "VALUE", type: "number", default: { source: "constant", value: "10" } }])).toEqual([
      "n: the default isn't a valid number.",
    ]);
  });

  it("requires a resource query to list its fields - never select everything", () => {
    expect(validateVariables([{ ...resource("r"), query: { where: {} } }])).toEqual(["r: the query must list its fields."]);
  });

  it("checks each emit against the kind's events", () => {
    expect(
      validateVariables([
        { name: "v", kind: "VALUE", type: "text", emits: { "update:value": "onVChange" } },
        { name: "c", kind: "CALL", target: { type: "WORKFLOW", workflow: "w" }, emits: { load: "x", success: "" } },
      ]),
    ).toEqual(['c: a Call has no event "load".', 'c: the "success" event has no function.']);
  });

  it("requires a call target", () => {
    const pick = "c: pick a function, a workflow, or a table and what to do (create, update, delete).";
    expect(validateVariables([{ name: "c", kind: "CALL", target: { type: "WORKFLOW" } }])).toEqual([pick]);
    expect(validateVariables([{ name: "c", kind: "CALL", target: { type: "TABLE", resource: "t", action: "UPSERT" } }])).toEqual([pick]);
  });

  it("takes a table write, whose update or delete names its row", () => {
    const table = (action: string, input?: Record<string, unknown>) => ({ name: "c", kind: "CALL", target: { type: "TABLE", resource: "t", action }, input });
    expect(validateVariables([table("CREATE", { data: { nombre: "{{vars.nombre.value}}" } }), { name: "nombre", kind: "VALUE", type: "text" }])).toEqual([]);
    expect(validateVariables([table("UPDATE", { pk: 7, data: { estado: "OK" } })])).toEqual([]);
    expect(validateVariables([table("DELETE", { where: { id: { _eq: 7 } } })])).toEqual([]);
    // No input: execute(input) gives it at run time.
    expect(validateVariables([table("DELETE")])).toEqual([]);
    expect(validateVariables([table("UPDATE", { data: { estado: "OK" } })])).toEqual(['c: a table update names its row - "pk" or "where" in the input.']);
  });

  it("checks the record's events", () => {
    expect(validateRecordConfig(undefined)).toEqual([]);
    expect(validateRecordConfig({ emits: { save: "onSave", "before:save": "check" } })).toEqual([]);
    expect(validateRecordConfig({ emits: { submit: "x", load: "" } })).toEqual(['record: a Record has no event "submit".', 'record: the "load" event has no function.']);
    expect(validateRecordConfig("x")).toEqual(["record: must be an object."]);
  });

  it("knows the page's record without it being defined", () => {
    expect(validateVariables([resource("items", { factura: { _eq: "{{vars.record.data.id}}" } })])).toEqual([]);
    expect(variableDependencies(resource("items", { factura: { _eq: "{{vars.record.data.id}}" } }))).toEqual(["record"]);
  });

  it("rejects references to variables that don't exist", () => {
    expect(validateVariables([resource("r", { id: { _eq: "{{vars.missing.value}}" } })])).toEqual([
      "r: uses {{vars.missing}}, which doesn't exist.",
    ]);
  });

  it("rejects a dependency loop", () => {
    expect(
      validateVariables([
        { name: "a", kind: "VALUE", type: "number", default: { source: "formula", formula: "{{vars.b.data}}" } },
        resource("b", { id: { _eq: "{{vars.a.value}}" } }),
      ]),
    ).toEqual(["These variables depend on each other in a loop: a → b → a."]);
  });
});

describe("variableDependencies()", () => {
  it("reads the variables a resource's query, a call's input and a formula default use", () => {
    expect(variableDependencies(resource("r", { _or: [{ a: { _eq: "{{vars.x.value}}" } }, { b: { _eq: "{{ vars.y.value }}" } }] }))).toEqual(["x", "y"]);
    expect(variableDependencies({ name: "c", kind: "CALL", target: { type: "FUNCTION", resource: "f" }, input: { n: "{{vars.z.value}}" } })).toEqual(["z"]);
    expect(variableDependencies({ name: "v", kind: "VALUE", type: "number", default: { source: "formula", formula: "{{vars.q.data}} * 2" } })).toEqual(["q"]);
  });
});

describe("resourceQueryColumns", () => {
  it("lists what a query reads: its fields, its order and its filter's fields", () => {
    expect(resourceQueryColumns({
      fields: "id, razon_social,cliente.nombre",
      order_by: "-fecha,id",
      where: { _and: [{ estado: { _eq: "A" } }, { _or: [{ total: { _gt: 0 } }, { _not: { anulada: { _eq: true } } }] }] },
    })).toEqual(["id", "razon_social", "cliente.nombre", "fecha", "estado", "total", "anulada"]);
    expect(resourceQueryColumns({ fields: "" })).toEqual([]);
  });
});

